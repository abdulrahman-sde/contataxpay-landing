/**
 * Searchable country picker. Same behaviour as the app's CountrySelect; the trigger and the
 * search box look like the app's Input (--ui-field-* tokens).
 */
export function CountrySelect({
  value,
  onChange,
  invalid,
}: {
  value: string
  onChange: (code: string) => void
  invalid?: boolean
}) {
  const { t } = useLanguage()
  const s1 = t.landing.hireAccountant.form.step1
  const countries = t.countries as Record<string, string>
  const [open, setOpen] = useState(false)
  const [query, setQuery] = useState("")
  const rootRef = useRef<HTMLDivElement>(null)
  const searchRef = useRef<HTMLInputElement>(null)

  const nameOf = (c: { code: string; name: string }) => countries[c.code] || c.name
  const q = query.toLowerCase()
  const filtered = ALL_COUNTRIES.filter((c) => c.name.toLowerCase().includes(q) || nameOf(c).toLowerCase().includes(q))
  const selected = ALL_COUNTRIES.find((c) => c.code === value)

  useEffect(() => {
    const onDown = (e: MouseEvent) => {
      if (rootRef.current && !rootRef.current.contains(e.target as Node)) {
        setOpen(false)
        setQuery("")
      }
    }
    document.addEventListener("mousedown", onDown)
    return () => document.removeEventListener("mousedown", onDown)
  }, [])

  useEffect(() => {
    if (open) searchRef.current?.focus()
  }, [open])

  return (
    <div className="relative" ref={rootRef}>
      <button
        type="button"
        aria-haspopup="listbox"
        aria-expanded={open}
        data-invalid={invalid || undefined}
        onClick={() => setOpen((v) => !v)}
        className="flex h-[var(--ui-field-h,40px)] w-full items-center justify-between gap-2 rounded-control border-2 border-solid border-[color:var(--ui-field-border)] bg-[var(--ui-field-bg)] px-3.5 text-left text-sm text-[color:var(--ui-field-ink)] hover:border-[color:var(--ui-field-border-hover)] focus-visible:border-[color:var(--ui-field-border-focus)] focus-visible:outline-none data-[invalid=true]:border-red-500"
      >
        <span className={cn("truncate", !selected && "text-[color:var(--ui-field-placeholder)]")}>
          {selected ? nameOf(selected) : s1.placeholder}
        </span>
        <ChevronDown className={cn("size-4 shrink-0 text-slate-400 transition-transform", open && "rotate-180")} />
      </button>

      {open && (
        <div className="absolute z-50 mt-1.5 w-full overflow-hidden rounded-control bg-white shadow-[0_18px_40px_-16px_rgba(15,23,42,0.25)] ring-1 ring-slate-900/[0.08]">
          <div className="relative border-b border-slate-100 p-2">
            <Search className="pointer-events-none absolute top-1/2 left-5 size-4 -translate-y-1/2 text-slate-400" />
            <input
              ref={searchRef}
              type="text"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder={s1.searchPlaceholder}
              className="h-9 w-full rounded-[10px] border-2 border-solid border-[color:var(--ui-field-border)] bg-white pr-3 pl-9 text-sm placeholder:text-[color:var(--ui-field-placeholder)] focus-visible:border-[color:var(--ui-field-border-focus)] focus-visible:outline-none"
            />
          </div>
          <ul role="listbox" className="max-h-64 overflow-y-auto p-1">
            {filtered.length > 0 ? (
              filtered.map((c) => {
                const isSel = c.code === value
                return (
                  <li key={c.code}>
                    <button
                      type="button"
                      role="option"
                      aria-selected={isSel}
                      onClick={() => {
                        onChange(c.code)
                        setOpen(false)
                        setQuery("")
                      }}
                      className={cn(
                        "flex w-full items-center justify-between rounded-lg px-3 py-2 text-left text-sm text-slate-700 hover:bg-slate-50",
                        isSel && "bg-blue-50/70 font-medium text-slate-900",
                      )}
                    >
                      {nameOf(c)}
                      {isSel && <Check className="size-4 text-[#3563e9]" />}
                    </button>
                  </li>
                )
              })
            ) : (
              <li className="px-3 py-2 text-sm text-slate-500">{s1.noCountriesFound}</li>
            )}
          </ul>
        </div>
      )}
    </div>
  )
}
